-- Plantao Clima - script do banco (Oracle 12c+ e H2 MODE=Oracle)
-- 6 tabelas: regiao, idoso, voluntario, vinculo_cuidado (N:N), alerta, checagem

CREATE TABLE regiao (
  id_regiao   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR2(80)  NOT NULL,
  cidade      VARCHAR2(80)  NOT NULL,
  uf          CHAR(2)       NOT NULL,
  latitude    NUMBER(9,6),
  longitude   NUMBER(9,6),
  CONSTRAINT uk_regiao UNIQUE (nome, cidade)
);

-- so o ano de nascimento (minimizacao de dados); a regra 60+ fica no Java
CREATE TABLE idoso (
  id_idoso            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_regiao           NUMBER        NOT NULL,
  nome                VARCHAR2(80)  NOT NULL,
  ano_nascimento      NUMBER(4)     NOT NULL,
  telefone            VARCHAR2(11),
  telefone_fixo       VARCHAR2(10),
  endereco_ref        VARCHAR2(120),
  contato_familiar    VARCHAR2(80),
  mora_sozinho        CHAR(1) DEFAULT 'S' NOT NULL,
  condicao_cronica    CHAR(1) DEFAULT 'N' NOT NULL,
  sem_ventilacao      CHAR(1) DEFAULT 'N' NOT NULL,
  mobilidade_reduzida CHAR(1) DEFAULT 'N' NOT NULL,
  area_risco          CHAR(1) DEFAULT 'N' NOT NULL,
  consentimento_em    DATE          NOT NULL,
  consentido_por      VARCHAR2(12)  NOT NULL,
  ativo               CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT fk_idoso_regiao FOREIGN KEY (id_regiao) REFERENCES regiao(id_regiao),
  CONSTRAINT ck_idoso_ano   CHECK (ano_nascimento BETWEEN 1900 AND 2100),
  CONSTRAINT ck_idoso_flags CHECK (mora_sozinho IN ('S','N') AND condicao_cronica IN ('S','N')
                                   AND sem_ventilacao IN ('S','N') AND mobilidade_reduzida IN ('S','N')
                                   AND area_risco IN ('S','N') AND ativo IN ('S','N')),
  CONSTRAINT ck_idoso_consent CHECK (consentido_por IN ('PROPRIO','RESPONSAVEL')),
  CONSTRAINT ck_idoso_tel CHECK (ativo = 'N' OR telefone IS NOT NULL OR telefone_fixo IS NOT NULL)
);

CREATE TABLE voluntario (
  id_voluntario NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_regiao     NUMBER       NOT NULL,
  nome          VARCHAR2(80) NOT NULL,
  telefone      VARCHAR2(11) NOT NULL,
  tipo          VARCHAR2(12) NOT NULL,
  ativo         CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT fk_vol_regiao FOREIGN KEY (id_regiao) REFERENCES regiao(id_regiao),
  CONSTRAINT uk_vol_tel UNIQUE (telefone),
  CONSTRAINT ck_vol_tipo CHECK (tipo IN ('VIZINHO','FAMILIAR','SINDICO','IGREJA','ACS','OUTRO')),
  CONSTRAINT ck_vol_ativo CHECK (ativo IN ('S','N'))
);

-- associativa N:N idoso x voluntario
CREATE TABLE vinculo_cuidado (
  id_idoso      NUMBER      NOT NULL,
  id_voluntario NUMBER      NOT NULL,
  papel         VARCHAR2(8) NOT NULL,
  desde         DATE        NOT NULL,
  CONSTRAINT pk_vinculo PRIMARY KEY (id_idoso, id_voluntario),
  CONSTRAINT fk_vinc_idoso FOREIGN KEY (id_idoso) REFERENCES idoso(id_idoso),
  CONSTRAINT fk_vinc_vol   FOREIGN KEY (id_voluntario) REFERENCES voluntario(id_voluntario),
  CONSTRAINT ck_vinc_papel CHECK (papel IN ('TITULAR','RESERVA')),
  CONSTRAINT uk_vinc_papel UNIQUE (id_idoso, papel)
);

-- alerta de calor extremo ou chuva forte; temp_max so faz sentido em CALOR
CREATE TABLE alerta (
  id_alerta   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_regiao   NUMBER       NOT NULL,
  tipo        VARCHAR2(5)  NOT NULL,
  data_alerta DATE         NOT NULL,
  nivel       VARCHAR2(10) NOT NULL,
  temp_max    NUMBER(4,1),
  origem      VARCHAR2(12) NOT NULL,
  fonte_aviso VARCHAR2(200),
  criado_em   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_alerta_regiao FOREIGN KEY (id_regiao) REFERENCES regiao(id_regiao),
  CONSTRAINT uk_alerta UNIQUE (id_regiao, data_alerta, tipo),
  CONSTRAINT ck_alerta_tipo CHECK (tipo IN ('CALOR','CHUVA')),
  CONSTRAINT ck_alerta_nivel CHECK (nivel IN ('OBSERVACAO','ATENCAO','ALERTA','MAXIMO')),
  CONSTRAINT ck_alerta_origem CHECK (origem IN ('INMET','DEFESA_CIVIL','OPEN_METEO','FLOODGUARD','MANUAL'))
);

-- tentativa 1 = titular, tentativa 2 = reserva
CREATE TABLE checagem (
  id_checagem       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alerta         NUMBER       NOT NULL,
  id_idoso          NUMBER       NOT NULL,
  id_voluntario     NUMBER       NOT NULL,
  tentativa         NUMBER(1)    DEFAULT 1 NOT NULL,
  resultado         VARCHAR2(12) DEFAULT 'PENDENTE' NOT NULL,
  canal             VARCHAR2(8),
  data_hora         TIMESTAMP,
  observacao        VARCHAR2(300),
  registrado_depois CHAR(1) DEFAULT 'N' NOT NULL,
  CONSTRAINT fk_chk_alerta FOREIGN KEY (id_alerta) REFERENCES alerta(id_alerta),
  CONSTRAINT fk_chk_idoso  FOREIGN KEY (id_idoso) REFERENCES idoso(id_idoso),
  CONSTRAINT fk_chk_vol    FOREIGN KEY (id_voluntario) REFERENCES voluntario(id_voluntario),
  CONSTRAINT uk_chk UNIQUE (id_alerta, id_idoso, tentativa),
  CONSTRAINT ck_chk_tent CHECK (tentativa IN (1,2)),
  CONSTRAINT ck_chk_res  CHECK (resultado IN ('PENDENTE','OK','ATENCAO','URGENTE','NAO_ATENDEU')),
  CONSTRAINT ck_chk_canal CHECK (canal IN ('LIGACAO','VISITA','MENSAGEM')),
  CONSTRAINT ck_chk_depois CHECK (registrado_depois IN ('S','N'))
);

