-- R1: cobertura de cada alerta por regiao (CTE + JOIN + SUM/COUNT + percentual)
-- critico = alguem nao atendeu, nao ha ligacao pendente e ninguem conseguiu contato (mesmo criterio do painel)
WITH por_idoso AS (
  SELECT a.id_alerta, a.id_regiao, a.tipo, a.nivel, i.id_idoso,
         MAX(CASE WHEN c.resultado IN ('OK','ATENCAO','URGENTE') THEN 1 ELSE 0 END) AS contatado,
         MAX(CASE WHEN c.resultado IN ('OK','ATENCAO','URGENTE')
                   AND c.data_hora <= a.criado_em + INTERVAL '4' HOUR THEN 1 ELSE 0 END) AS ate_4h,
         MAX(CASE WHEN c.resultado = 'URGENTE' THEN 1 ELSE 0 END) AS urgente,
         MAX(CASE WHEN c.resultado = 'NAO_ATENDEU' THEN 1 ELSE 0 END) AS nao_atendeu,
         MAX(CASE WHEN c.resultado = 'PENDENTE' THEN 1 ELSE 0 END) AS pendente
  FROM alerta a
  JOIN idoso i ON i.id_regiao = a.id_regiao AND i.ativo = 'S'
  LEFT JOIN checagem c ON c.id_alerta = a.id_alerta AND c.id_idoso = i.id_idoso
  WHERE a.data_alerta = DATE '2026-11-17'
  GROUP BY a.id_alerta, a.id_regiao, a.tipo, a.nivel, i.id_idoso
)
SELECT r.nome AS regiao, r.cidade, p.tipo, p.nivel,
       COUNT(*) AS idosos_ativos,
       SUM(p.contatado) AS contatados,
       SUM(p.ate_4h) AS contatados_ate_4h,
       SUM(p.urgente) AS urgentes,
       SUM(CASE WHEN p.nao_atendeu = 1 AND p.pendente = 0 AND p.contatado = 0 THEN 1 ELSE 0 END) AS criticos,
       ROUND(100.0 * SUM(p.ate_4h) / NULLIF(COUNT(*), 0), 1) AS pct_ate_4h
FROM por_idoso p
JOIN regiao r ON r.id_regiao = p.id_regiao
GROUP BY r.id_regiao, r.nome, r.cidade, p.id_alerta, p.tipo, p.nivel
ORDER BY pct_ate_4h;

-- R2: furos na rede - idosos ativos com menos de 2 cuidadores ativos (LEFT JOIN + HAVING)
SELECT r.nome AS regiao, i.nome AS idoso, COUNT(v.id_voluntario) AS cuidadores_ativos
FROM idoso i
JOIN regiao r ON r.id_regiao = i.id_regiao
LEFT JOIN vinculo_cuidado vc ON vc.id_idoso = i.id_idoso
LEFT JOIN voluntario v ON v.id_voluntario = vc.id_voluntario AND v.ativo = 'S'
WHERE i.ativo = 'S'
GROUP BY r.nome, i.id_idoso, i.nome
HAVING COUNT(v.id_voluntario) < 2
ORDER BY cuidadores_ativos, r.nome;

-- R3: carga e taxa de "nao atendeu" por voluntario
SELECT v.nome AS voluntario, v.tipo,
       COUNT(DISTINCT vc.id_idoso) AS idosos_sob_cuidado,
       COUNT(DISTINCT c.id_checagem) AS ligacoes_feitas,
       COUNT(DISTINCT CASE WHEN c.resultado = 'NAO_ATENDEU' THEN c.id_checagem END) AS nao_atendeu,
       ROUND(100.0 * COUNT(DISTINCT CASE WHEN c.resultado = 'NAO_ATENDEU' THEN c.id_checagem END)
             / NULLIF(COUNT(DISTINCT c.id_checagem), 0), 1) AS pct_nao_atendeu
FROM voluntario v
LEFT JOIN vinculo_cuidado vc ON vc.id_voluntario = v.id_voluntario
LEFT JOIN checagem c ON c.id_voluntario = v.id_voluntario AND c.resultado <> 'PENDENTE'
WHERE v.ativo = 'S'
GROUP BY v.id_voluntario, v.nome, v.tipo
ORDER BY pct_nao_atendeu DESC NULLS LAST;

-- Painel: criticos do alerta (nao atendeu, nada pendente, nenhum contato com sucesso)
-- cobre o idoso sem reserva: titular nao atendeu e ja vira critico
SELECT i.nome, i.endereco_ref, i.contato_familiar, MAX(c.data_hora) AS ultima_tentativa
FROM checagem c
JOIN idoso i ON i.id_idoso = c.id_idoso
WHERE c.id_alerta = 1 AND c.resultado = 'NAO_ATENDEU'
  AND NOT EXISTS (SELECT 1 FROM checagem ok
                  WHERE ok.id_alerta = c.id_alerta AND ok.id_idoso = c.id_idoso
                    AND ok.resultado IN ('OK','ATENCAO','URGENTE','PENDENTE'))
GROUP BY i.id_idoso, i.nome, i.endereco_ref, i.contato_familiar;
