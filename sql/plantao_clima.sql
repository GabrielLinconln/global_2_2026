-- =============================================================================
-- 1. TABELA REGIAO (Territorios monitorados - evolucao do modulo FloodGuard)
-- =============================================================================
CREATE TABLE REGIAO (
    ID_REGIAO       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR2(100) NOT NULL,
    BAIRRO_ZONA     VARCHAR2(100) NOT NULL,
    RISCO_CALOR     VARCHAR2(20)  NOT NULL,
    RISCO_CHUVA     VARCHAR2(20)  NOT NULL,
    REFERENCIA_UBS  VARCHAR2(120) NOT NULL,
    ATIVO           NUMBER(1)     DEFAULT 1 NOT NULL,
    CONSTRAINT UK_REGIAO_NOME        UNIQUE (NOME),
    CONSTRAINT CK_REGIAO_RISCO_CALOR CHECK (RISCO_CALOR IN ('BAIXO', 'MODERADO', 'ALTO')),
    CONSTRAINT CK_REGIAO_RISCO_CHUVA CHECK (RISCO_CHUVA IN ('BAIXO', 'MODERADO', 'ALTO')),
    CONSTRAINT CK_REGIAO_ATIVO       CHECK (ATIVO IN (0, 1))
);

-- =============================================================================
-- 2. TABELA IDOSO (Dados minimos LGPD: apenas ano de nascimento + consentimento)
-- =============================================================================
CREATE TABLE IDOSO (
    ID_IDOSO            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                VARCHAR2(120) NOT NULL,
    TELEFONE            VARCHAR2(25)  NOT NULL,
    ANO_NASCIMENTO      NUMBER(4)     NOT NULL,
    ENDERECO_RESUMO     VARCHAR2(180) NOT NULL,
    DOENCA_CRONICA      NUMBER(1)     DEFAULT 0 NOT NULL,
    MOBILIDADE_REDUZIDA NUMBER(1)     DEFAULT 0 NOT NULL,
    CASA_SEM_VENTILACAO NUMBER(1)     DEFAULT 0 NOT NULL,
    AREA_RISCO          NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSENTIMENTO_LGPD  NUMBER(1)     NOT NULL,
    DATA_CONSENTIMENTO  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    OBSERVACOES         VARCHAR2(300),
    ID_REGIAO           NUMBER(10)    NOT NULL,
    ATIVO               NUMBER(1)     DEFAULT 1 NOT NULL,
    CRIADO_EM           TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_IDOSO_REGIAO      FOREIGN KEY (ID_REGIAO) REFERENCES REGIAO(ID_REGIAO),
    CONSTRAINT CK_IDOSO_ANO         CHECK (ANO_NASCIMENTO BETWEEN 1900 AND 1975),
    CONSTRAINT CK_IDOSO_CRONICA     CHECK (DOENCA_CRONICA IN (0, 1)),
    CONSTRAINT CK_IDOSO_MOBILIDADE  CHECK (MOBILIDADE_REDUZIDA IN (0, 1)),
    CONSTRAINT CK_IDOSO_VENTILACAO  CHECK (CASA_SEM_VENTILACAO IN (0, 1)),
    CONSTRAINT CK_IDOSO_AREA_RISCO  CHECK (AREA_RISCO IN (0, 1)),
    CONSTRAINT CK_IDOSO_LGPD        CHECK (CONSENTIMENTO_LGPD = 1),
    CONSTRAINT CK_IDOSO_ATIVO       CHECK (ATIVO IN (0, 1))
);

-- =============================================================================
-- 3. TABELA VOLUNTARIO (Vizinhos, familiares, sindicos e agentes comunitarios)
-- =============================================================================
CREATE TABLE VOLUNTARIO (
    ID_VOLUNTARIO      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME               VARCHAR2(120) NOT NULL,
    TELEFONE           VARCHAR2(25)  NOT NULL,
    RELACAO_COMUNIDADE VARCHAR2(80)  NOT NULL,
    DISPONIBILIDADE    VARCHAR2(80)  NOT NULL,
    ID_REGIAO          NUMBER(10)    NOT NULL,
    ATIVO              NUMBER(1)     DEFAULT 1 NOT NULL,
    CRIADO_EM          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_VOLUNTARIO_TEL    UNIQUE (TELEFONE),
    CONSTRAINT FK_VOLUNTARIO_REGIAO FOREIGN KEY (ID_REGIAO) REFERENCES REGIAO(ID_REGIAO),
    CONSTRAINT CK_VOLUNTARIO_ATIVO  CHECK (ATIVO IN (0, 1))
);

-- =============================================================================
-- 4. TABELA VINCULO_CUIDADO (Tabela associativa N:N entre IDOSO e VOLUNTARIO)
--    Define quem e o voluntario TITULAR e quem e o RESERVA de cada idoso
-- =============================================================================
CREATE TABLE VINCULO_CUIDADO (
    ID_VINCULO    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_IDOSO      NUMBER(10)   NOT NULL,
    ID_VOLUNTARIO NUMBER(10)   NOT NULL,
    PAPEL         VARCHAR2(20) NOT NULL,
    PRIORIDADE    NUMBER(2)    NOT NULL,
    CRIADO_EM     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_VINCULO_IDOSO      FOREIGN KEY (ID_IDOSO)      REFERENCES IDOSO(ID_IDOSO) ON DELETE CASCADE,
    CONSTRAINT FK_VINCULO_VOLUNTARIO FOREIGN KEY (ID_VOLUNTARIO) REFERENCES VOLUNTARIO(ID_VOLUNTARIO) ON DELETE CASCADE,
    CONSTRAINT UK_VINCULO_IDOSO_PAP  UNIQUE (ID_IDOSO, PAPEL),
    CONSTRAINT UK_VINCULO_IDOSO_VOL  UNIQUE (ID_IDOSO, ID_VOLUNTARIO),
    CONSTRAINT CK_VINCULO_PAPEL      CHECK (PAPEL IN ('TITULAR', 'RESERVA')),
    CONSTRAINT CK_VINCULO_PRIORIDADE CHECK (PRIORIDADE IN (1, 2))
);

-- =============================================================================
-- 5. TABELA ALERTA (Alertas climaticos de CALOR ou CHUVA - INMET/Defesa Civil)
-- =============================================================================
CREATE TABLE ALERTA (
    ID_ALERTA    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULO       VARCHAR2(140) NOT NULL,
    TIPO         VARCHAR2(20)  NOT NULL,
    SEVERIDADE   VARCHAR2(20)  NOT NULL,
    FONTE        VARCHAR2(60)  NOT NULL,
    DESCRICAO    VARCHAR2(400) NOT NULL,
    STATUS       VARCHAR2(20)  DEFAULT 'ATIVO' NOT NULL,
    ID_REGIAO    NUMBER(10),
    EMITIDO_EM   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ENCERRADO_EM TIMESTAMP,
    CONSTRAINT FK_ALERTA_REGIAO     FOREIGN KEY (ID_REGIAO) REFERENCES REGIAO(ID_REGIAO),
    CONSTRAINT CK_ALERTA_TIPO       CHECK (TIPO IN ('CALOR', 'CHUVA')),
    CONSTRAINT CK_ALERTA_SEVERIDADE CHECK (SEVERIDADE IN ('AMARELO', 'LARANJA', 'VERMELHO')),
    CONSTRAINT CK_ALERTA_STATUS     CHECK (STATUS IN ('ATIVO', 'ENCERRADO'))
);

-- =============================================================================
-- 6. TABELA CHECAGEM (Rodada de ligacoes, escalonamento e casos criticos)
-- =============================================================================
CREATE TABLE CHECAGEM (
    ID_CHECAGEM      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_ALERTA        NUMBER(10)    NOT NULL,
    ID_IDOSO         NUMBER(10)    NOT NULL,
    ID_VOLUNTARIO    NUMBER(10),
    PAPEL_ATUAL      VARCHAR2(20)  NOT NULL,
    PONTUACAO_RISCO  NUMBER(3)     NOT NULL,
    STATUS           VARCHAR2(30)  DEFAULT 'PENDENTE' NOT NULL,
    TENTATIVAS       NUMBER(2)     DEFAULT 0 NOT NULL,
    CHECKLIST_RESUMO VARCHAR2(300),
    OBSERVACAO       VARCHAR2(400),
    CRIADO_EM        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM    TIMESTAMP,
    CONSTRAINT FK_CHECAGEM_ALERTA     FOREIGN KEY (ID_ALERTA)     REFERENCES ALERTA(ID_ALERTA) ON DELETE CASCADE,
    CONSTRAINT FK_CHECAGEM_IDOSO      FOREIGN KEY (ID_IDOSO)      REFERENCES IDOSO(ID_IDOSO) ON DELETE CASCADE,
    CONSTRAINT FK_CHECAGEM_VOLUNTARIO FOREIGN KEY (ID_VOLUNTARIO) REFERENCES VOLUNTARIO(ID_VOLUNTARIO) ON DELETE SET NULL,
    CONSTRAINT UK_CHECAGEM_ETAPA      UNIQUE (ID_ALERTA, ID_IDOSO, PAPEL_ATUAL),
    CONSTRAINT CK_CHECAGEM_PAPEL      CHECK (PAPEL_ATUAL IN ('TITULAR', 'RESERVA', 'COORDENACAO')),
    CONSTRAINT CK_CHECAGEM_STATUS     CHECK (STATUS IN ('PENDENTE', 'ESTA_BEM', 'PRECISA_ATENCAO', 'PRECISA_AJUDA', 'NAO_ATENDEU', 'CRITICO')),
    CONSTRAINT CK_CHECAGEM_RISCO      CHECK (PONTUACAO_RISCO >= 0)
);

